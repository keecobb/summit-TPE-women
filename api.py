def require_api_key(x_api_key: str | None = Header(None)):
    """FastAPI dependency, applied to every route below except /health.
    No-ops entirely if SUMMIT_TPE_API_KEY isn't set (local dev default)."""
    if API_KEY is None:
        return
    if x_api_key is None or not secrets.compare_digest(x_api_key, API_KEY):
        raise HTTPException(status_code=401, detail="Missing or invalid X-API-Key header.")
 
 
def get_conn(sport: str):
    if sport not in DB_PATHS:
        raise HTTPException(status_code=404, detail=f"Unknown sport {sport!r} -- must be 'women' or 'men'.")
    db_path = DB_PATHS[sport]
    if not db_path.exists():
        raise HTTPException(status_code=503,
                             detail=f"{db_path.name} not found -- run build_cache.py --sport {sport} first.")
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    return conn


# Sport-scoped router -- every route registered on this (all of them below
# except /health) picks up a leading /{sport} path segment automatically,
# and FastAPI injects that segment into each handler's `sport` parameter
# by name, same as any other path param. Mounted onto `app` at the very
# bottom of this file via app.include_router(router).
router = APIRouter(prefix="/{sport}")
 
 
@app.get("/health")
def health():
    """Sport-agnostic -- reports both caches' status at once (not scoped
    under /{sport} like every other route), since this is the one endpoint
    that needs to answer "is the whole API up" without picking a sport
    first. refresh_pipeline.py's health-check gate runs against the
    workbook directly (check_data_health.py), not this endpoint -- this is
    for uptime monitoring / confirming a swapped-in cache is live."""
    sports = {}
    ok = True
    for sport, db_path in DB_PATHS.items():
        exists = db_path.exists()
        season = None
        if exists:
            conn = sqlite3.connect(db_path)
            conn.row_factory = sqlite3.Row
            row = conn.execute("SELECT value FROM meta WHERE key='season'").fetchone()
            season = row[0] if row else None
            conn.close()
        sports[sport] = {"cache_present": exists, "season": season}
        ok = ok and exists
    return {"ok": ok, "sports": sports}
 
 
@router.get("/teams", dependencies=[Depends(require_api_key)])
def list_teams(sport: str,
    
    tier: str | None = Query(None, description=f"Filter by tier: one of {list(VALID_LEVELS)} "
                                                 f"(\"P5\" is still accepted as an alias for High-Major)."),
    conference: str | None = Query(None),
    search: str | None = Query(None, description="Case-insensitive substring match on team name"),
    limit: int = Query(100, le=500),
    offset: int = 0,
):
    conn = get_conn(sport)
    tier = normalize_tier(tier)
    clauses, params = [], []
    if tier:
        clauses.append("tier = ?")
        params.append(tier)
    if conference:
        clauses.append("conference = ?")
        params.append(conference)
    if search:
        clauses.append("name LIKE ?")
        params.append(f"%{search}%")
    where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
    rows = conn.execute(
        f"SELECT team_id, name, division, conference, tier, current_rating, sos "
        f"FROM teams {where} ORDER BY current_rating DESC LIMIT ? OFFSET ?",
        params + [limit, offset],
    ).fetchall()
    conn.close()
    return [dict(r) for r in rows]
 
 
