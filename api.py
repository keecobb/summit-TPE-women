@app.get("/teams/{team_id}/fits", dependencies=[Depends(require_api_key)])
def get_team_fits(
    team_id: int,
    stat: str | None = Query(None, description=f"One of {list(CATEGORY_INFO)}. Omit to auto-pick this "
                                                 f"team's single biggest weakness from /teams/{{id}}/needs "
                                                 f"(that auto-pick is always league-wide, regardless of `level`). "
                                                 f"Ignored if `stats` is also given."),
    stats: list[str] | None = Query(
        None, description=f"Repeat for more than one category at once, e.g. "
                           f"?stats=per40_reb&stats=per40_blk -- one of {list(CATEGORY_INFO)} each. Ranks by "
                           f"the average of each candidate's league-wide z-score across all given categories "
                           f"(sign-flipped for turnovers) instead of a single raw value. Wins over `stat`."),
    limit: int = Query(15, le=100),
    min_games: int = Query(5, description="Exclude candidates with a thinner sample than this many games"),
    transfer_portal_only: bool = Query(
        False, description="Only include candidates confirmed in the transfer portal. Requires a "
                            "'Transfer Portal' column on the Players sheet + a rebuilt cache -- errors "
                            "clearly (404) if no transfer portal data has been loaded yet, instead of "
                            "silently returning an empty list."),
    level: str | None = Query(
        None, description=f"One of {list(VALID_LEVELS)}. Only consider candidates whose CURRENT team is "
                           f"at that tier -- e.g. level=Low-Major for a Low-Major team excludes every "
                           f"P5/Mid-Major player from the pool outright, instead of just labeling them."),
    role: str | None = Query(None, description=f"One of {ROLE_NAMES} -- resolved from THIS team's (team_id's) "
                                                f"own current roster via /teams/{{id}}/roles, and applied to "
                                                f"every candidate's projection. Ignored if `minutes` is given."),
    minutes: float | None = Query(None, description="Exact 0-40 minutes applied to every candidate's "
                                                      "projection. Wins over `role` if both are given."),
):
    """Reverse lookup: every player NOT on this roster, ranked by her
    PROJECTED contribution to `stat`/`stats` (or this team's biggest
    weakness, if neither is given) if she transferred in, optionally
    projected at a specific role or exact minutes on THIS team rather
    than each candidate's own auto-projected minutes. Each candidate is
    projected with the exact same math as /project, just run over the
    whole player pool at once. Every candidate includes current_division,
    current_tier/level, and class_year. By default this is a plain ranking
    by projected production, not filtered by recruiting realism -- pass
    `level` to restrict the candidate pool to one tier instead of just
    labeling unrealistic candidates (a P5 starter, etc) for manual skip."""
    conn = get_conn()
    try:
        return find_fits(conn, team_id, stat=stat, stats=stats, limit=limit, min_games=min_games,
                          transfer_portal_only=transfer_portal_only, level=level, role=role, minutes=minutes)
    except ProjectionError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    finally:
        conn.close()
 
 
class BatchPlayerRequest(BaseModel):
    player_id: int
    minutes: float | None = None
    role: str | None = None
 
 
class BatchProjectRequest(BaseModel):
    target_team_id: int
    players: list[BatchPlayerRequest]
 
 
@app.post("/project/batch", dependencies=[Depends(require_api_key)])
def project_batch_endpoint(body: BatchProjectRequest = Body(...)):
    """Project several players at the same target team in one call, plus
    a combined per-game total across all of them -- for evaluating a
    shortlist of transfer targets against open roster spots at once,
    instead of one /project call per name. See project_batch()'s
    docstring for exactly what the combined total does and doesn't mean
    (it's a sum of individual projections, not a re-solved team rating)."""
    conn = get_conn()
    try:
        result = project_batch(
            conn, body.target_team_id,
            [dict(player_id=p.player_id, minutes=p.minutes, role=p.role) for p in body.players],
        )
    except ProjectionError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    finally:
        conn.close()
    return result
 
 
