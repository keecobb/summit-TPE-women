"""Summit TPE transfer-calculator API. Thin REST wrapper around
projection.py + the summit_tpe_cache.sqlite built by build_cache.py --
simple enough for a website today and a mobile app later, since both just
speak JSON over HTTP rather than needing this logic ported into each
client.
 
Run:
    uvicorn api:app --reload --port 8000
 
Then, e.g.:
    GET /players?search=troxell
    GET /teams?tier=High-Major
    GET /teams/4/roles
    GET /project?player_id=1234&target_team_id=4&minutes=28
    GET /project?player_id=1234&target_team_id=4&role=starter
 
Interactive docs (auto-generated by FastAPI) at /docs once it's running.
 
---- Access control (env-driven, safe by default for local dev) ----
 
Two env vars control who can reach this API once it's not just running on
your own machine:
 
  SUMMIT_TPE_API_KEY
      If set, every route except /health requires a matching
      "X-API-Key: <value>" request header, or it 401s. If UNSET (the
      default), no key is required at all -- so local `curl`/`/docs`
      testing keeps working with zero setup. Generate one with e.g.
      `python -c "import secrets; print(secrets.token_urlsafe(32))"` and
      set it as an environment variable on whatever host runs this, then
      give the same value to your frontend to send on every request.
 
  SUMMIT_TPE_ALLOWED_ORIGINS
      Comma-separated list of origins allowed to call this API from a
      browser (e.g. "https://mysite.com,https://www.mysite.com"). Defaults
      to "*" (any origin) for local dev. Set this to your real domain(s)
      before a real website points at this API -- "*" plus no API key is
      an open API to the entire internet.
 
Neither is required to run this locally. Both print a startup warning if
left at their insecure defaults, so it's obvious in the logs (not just in
this docstring) that they haven't been configured yet.
"""
 
