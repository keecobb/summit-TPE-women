@router.get("/teams/{team_id}/roles", dependencies=[Depends(require_api_key)])
def get_team_roles(sport: str,
    team_id: int):
    """Role-based minutes for this team, computed from its own current
    roster (Solidified Starter/Sixth Man/Role Player/Depth Piece) -- lets a
    UI show a coach e.g. 'Solidified Starter (31.2 min)' as a pickable
    option before running /project with role=starter, instead of only a
    free-text minutes field. A player counts as a Solidified Starter once
    she starts >= 65% of the games she's played (ROLE_STARTER_START_PCT in
    projection.py); Sixth Man is the single highest-avg-minutes player
    among those starting under 35% of games. Because that's a real,
    games-started-rate classification and not a fixed top-5-by-minutes
    cut, a given team's roster won't always show exactly 5 Solidified
    Starters -- these are only the confirmed, for-sure ones, which is also
    why the label says "Solidified" rather than plain "Starter". See the
    comment block above ROLE_STARTER_START_PCT in projection.py for the
    full rationale. Also includes `roster_roles`, the same classification
    applied per-player in roster order, for a UI that wants to label every
    player on the roster with her role rather than just the 4 aggregate
    numbers."""
    conn = get_conn(sport)
    team = conn.execute("SELECT team_id, name FROM teams WHERE team_id = ?", (team_id,)).fetchone()
    if team is None:
        conn.close()
        raise HTTPException(status_code=404, detail=f"No team with id {team_id}")
    roles = team_roles(conn, team_id)
    conn.close()
    # team_roles() already includes team_id in its return dict -- passing
    # team_id=team_id here too used to raise "dict() got multiple values
    # for keyword argument 'team_id'" on EVERY call (found by actually
    # exercising this endpoint against the live cache, not just reading
    # the code -- it 500'd for every team tested, not just some).
    return dict(team_name=team["name"], **roles)


@router.get("/class-archetypes", dependencies=[Depends(require_api_key)])
def get_class_archetypes(sport: str):
    """Real averages of THIS season's actual players, grouped by class
    year (FR/SO/JR/SR), team level (High-Major/Mid-Major/Low-Major, from
    each player's own current team), a minutes-based archetype (Day 1
    Starter/Role Player/Depth Piece), and (when the sample's big enough)
    position (G/F/C) -- see ARCHETYPE_DAY1_STARTER_MIN_MINUTES/
    ARCHETYPE_DEPTH_PIECE_MAX_MINUTES in projection.py for the exact
    minutes cutoffs. Powers Team Builder's custom-entry preset picker for
    a true freshman, a JUCO transfer (entering as a Sophomore or Junior),
    or a lower-level (D2/NAIA) transfer (entering at any class) -- instead
    of typing a stat line from nothing, a coach starts from "what did an
    actual Mid-Major Day 1 Starter Sophomore average this season" (real
    production at THAT class year, not a freshman-only number stretched to
    fit) and edits from there, optionally narrowed to Great/Good/Average
    production tiers within that bucket (see PRODUCTION_TIER_LABELS).
    thin_sample rows (short-sample cameos) are excluded so a 2-minute
    appearance doesn't skew a bucket's average -- same convention as every
    other real-data aggregate on the site. A cell with zero qualifying
    players this season comes back as `{"player_count": 0}` (no fabricated
    numbers) rather than being omitted."""
    conn = get_conn(sport)
    archetypes = class_archetypes(conn)
    conn.close()
    return dict(
        archetype_labels=ARCHETYPE_LABELS,
        production_tier_labels=PRODUCTION_TIER_LABELS,
        classes=archetypes,
    )


